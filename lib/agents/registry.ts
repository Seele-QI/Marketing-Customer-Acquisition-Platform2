const BY_NAME = new Map(AGENT_DEFINITIONS.map((agent) => [agent.name, agent]))

export function getAgentById(id: string): AgentDefinition | undefined {
  return BY_ID.get(id)
}

export function getAgentByName(name: string): AgentDefinition | undefined {
  return BY_NAME.get(name)
}

export function listAgentsByGroup(group: AgentDefinition["group"]): AgentDefinition[] {
  return AGENT_DEFINITIONS.filter((agent) => agent.group === group)
}

